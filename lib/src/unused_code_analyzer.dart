import 'dart:io';

import 'package:analyzer/dart/analysis/analysis_context_collection.dart';
import 'package:analyzer/dart/analysis/results.dart';
import 'package:path/path.dart' as p;
import 'package:yaml/yaml.dart';

import 'config.dart';
import 'element_keys.dart';
import 'report.dart';
import 'unit_scanner.dart';

/// Thrown when the project cannot be analyzed at all.
class AnalysisSetupException implements Exception {
  AnalysisSetupException(this.message);

  final String message;

  @override
  String toString() => message;
}

/// Top-level directories that never hold the project's own Dart sources.
const _skippedDirectories = {
  'build',
  'android',
  'ios',
  'macos',
  'linux',
  'windows',
  'web',
  'node_modules',
};

const _ignoreFileMarker = 'unused_code:ignore_file';

const _testRoots = ['test/', 'integration_test/', 'test_driver/'];

final _generatedHeader = RegExp(
  r'GENERATED CODE|Generated file|File generated by|DO NOT EDIT',
  caseSensitive: false,
);

/// Finds unused files, declarations and members in one Dart package.
class UnusedCodeAnalyzer {
  UnusedCodeAnalyzer(String root, this.config)
    : root = p.normalize(p.absolute(root));

  final String root;
  final UnusedCodeConfig config;

  /// Runs the analysis. Throws [AnalysisSetupException] when the directory
  /// is not a resolved Dart package.
  Future<UnusedCodeReport> run() async {
    final watch = Stopwatch()..start();
    final pubspec = File(p.join(root, 'pubspec.yaml'));
    if (!pubspec.existsSync()) {
      throw AnalysisSetupException('No pubspec.yaml in $root');
    }
    if (!File(p.join(root, '.dart_tool', 'package_config.json')).existsSync()) {
      throw AnalysisSetupException(
        'Dependencies are not resolved in $root. '
        'Run `flutter pub get` (or `dart pub get`) first.',
      );
    }

    final files = _discover();
    final mode = _resolveMode(pubspec, files);
    final sources = <String, String>{};
    final scans = <String, UnitScan>{};
    final apiKeys = <String>{};
    final inheritedCache = <String, List<String>>{};
    final fileSet = files.toSet();

    final collection = AnalysisContextCollection(includedPaths: [root]);
    try {
      for (final path in files) {
        if (scans.containsKey(path)) continue; // reached as a part already
        final session = collection.contextFor(path).currentSession;
        final result = await session.getResolvedLibrary(path);
        if (result is! ResolvedLibraryResult) continue;

        final rel = _relative(path);
        if (mode == ProjectMode.package && _isPublicLibrary(rel)) {
          for (final e in result.element.exportNamespace.definedNames2.values) {
            final key = keyOf(e);
            if (key != null) apiKeys.add(key);
          }
        }
        for (final unit in result.units) {
          if (!fileSet.contains(unit.path) || scans.containsKey(unit.path)) {
            continue;
          }
          final unitRel = _relative(unit.path);
          sources[unit.path] = unit.content;
          scans[unit.path] = UnitScanner(
            unit: unit.unit,
            config: config,
            collect: _isReportable(unitRel, unit.content),
            content: unit.content,
            path: unit.path,
            inheritedCache: inheritedCache,
          ).run();
        }
      }
    } finally {
      await collection.dispose();
    }

    final reachable = _reachable(files, scans, mode);
    final ignoredFiles = {
      for (final e in sources.entries)
        if (e.value.contains(_ignoreFileMarker)) e.key,
    };
    final live = _liveKeys(scans, reachable, apiKeys, ignoredFiles);

    bool isUsed(Declared d) {
      if (d.keepReason != null || live.contains(d.key)) return true;
      final containerKey = d.containerKey;
      return containerKey != null &&
          mode == ProjectMode.package &&
          apiKeys.contains(containerKey);
    }

    final findings = <Finding>[];
    for (final path in files) {
      final rel = _relative(path);
      final content = sources[path];
      if (content == null || !_isReportable(rel, content)) continue;
      if (!reachable.contains(path)) {
        findings.add(
          Finding(
            category: FindingCategory.file,
            kind: 'file',
            name: rel,
            path: rel,
            line: 1,
            column: 1,
            lines: '\n'.allMatches(content).length + 1,
          ),
        );
        continue;
      }
      final declarations = scans[path]?.declarations ?? const <Declared>[];
      final unusedContainers = <String>{};
      for (final d in declarations) {
        if (isUsed(d)) continue;
        final containerKey = d.containerKey;
        if (containerKey != null && unusedContainers.contains(containerKey)) {
          continue; // the whole type is reported already
        }
        if (d.category == FindingCategory.declaration) {
          unusedContainers.add(d.key);
        }
        findings.add(
          Finding(
            category: d.category,
            kind: d.kind,
            name: d.name,
            container: d.container,
            path: rel,
            line: d.line,
            column: d.column,
            lines: d.lines,
            isWidget: d.isWidget,
          ),
        );
      }
    }

    watch.stop();
    return UnusedCodeReport(
      root: root,
      mode: mode.name,
      filesAnalyzed: scans.length,
      elapsed: watch.elapsed,
      findings: findings,
    );
  }

  /// Mark-and-sweep over top-level declarations: a reference counts only
  /// when it sits in code that is itself alive. Roots are code outside
  /// `lib/` (tests, `bin/`, tools), excluded and ignored files, references
  /// outside any declaration, kept declarations and, for a package, its
  /// exported API.
  Set<String> _liveKeys(
    Map<String, UnitScan> scans,
    Set<String> reachable,
    Set<String> apiKeys,
    Set<String> ignoredFiles,
  ) {
    final conditional = <String, List<Set<String>>>{};
    final visibleForTesting = <String>{};
    final declared = <String>{};
    final queue = <String>[...apiKeys];
    final testRoots = <String>{};

    for (final scan in scans.values) {
      if (!reachable.contains(scan.path)) continue;
      final rel = _relative(scan.path);
      for (final d in scan.declarations) {
        declared.add(d.key);
        if (d.visibleForTesting) visibleForTesting.add(d.key);
      }
      queue.addAll(scan.rootKeys);
      final isRootFile =
          !_isLib(rel) || _isExcluded(rel) || ignoredFiles.contains(scan.path);
      scan.references.forEach((owner, refs) {
        if (_isTest(rel)) {
          testRoots.addAll(refs);
        } else if (owner == null || isRootFile) {
          queue.addAll(refs);
        } else {
          (conditional[owner] ??= []).add(refs);
        }
      });
    }
    for (final key in testRoots) {
      // Without test usage, tests may only keep @visibleForTesting code (and
      // things that are not reportable declarations, like mocks) alive.
      if (config.countTestUsage ||
          visibleForTesting.contains(key) ||
          !declared.contains(key)) {
        queue.add(key);
      }
    }

    final live = <String>{};
    while (queue.isNotEmpty) {
      final key = queue.removeLast();
      if (!live.add(key)) continue;
      for (final refs in conditional[key] ?? const <Set<String>>[]) {
        queue.addAll(refs);
      }
    }
    return live;
  }

  String _relative(String path) =>
      p.posix.joinAll(p.split(p.relative(path, from: root)));

  bool _isTest(String rel) => _testRoots.any(rel.startsWith);

  bool _isLib(String rel) => rel.startsWith('lib/');

  bool _isPublicLibrary(String rel) =>
      _isLib(rel) && !rel.substring(4).contains('/');

  bool _isGenerated(String rel, String content) {
    if (config.generatedGlobs.any((g) => g.matches(rel))) return true;
    final head = content.length > 600 ? content.substring(0, 600) : content;
    for (final line in head.split('\n')) {
      final t = line.trimLeft();
      if (!t.startsWith('//')) {
        if (t.isEmpty) continue;
        break;
      }
      if (_generatedHeader.hasMatch(t)) return true;
    }
    return false;
  }

  bool _isExcluded(String rel) =>
      config.excludeGlobs.any((g) => g.matches(rel));

  /// Only hand-written, non-excluded code under `lib/` is ever reported.
  bool _isReportable(String rel, String content) =>
      _isLib(rel) &&
      !_isExcluded(rel) &&
      !_isGenerated(rel, content) &&
      !content.contains(_ignoreFileMarker);

  bool _isEntry(String rel, ProjectMode mode) {
    if (!_isLib(rel)) return true; // bin/, test/, tool/, ...
    if (_isExcluded(rel)) return true;
    if (config.entryGlobs.any((g) => g.matches(rel))) return true;
    if (_isPublicLibrary(rel)) {
      if (mode == ProjectMode.package) return true;
      if (p.posix.basename(rel).startsWith('main')) return true;
    }
    return false;
  }

  Set<String> _reachable(
    List<String> files,
    Map<String, UnitScan> scans,
    ProjectMode mode,
  ) {
    final seen = <String>{};
    final queue = <String>[
      for (final f in files)
        if (_isEntry(_relative(f), mode)) f,
    ];
    while (queue.isNotEmpty) {
      final next = queue.removeLast();
      if (!seen.add(next)) continue;
      queue.addAll(scans[next]?.edges ?? const <String>{});
    }
    return seen;
  }

  ProjectMode _resolveMode(File pubspec, List<String> files) {
    if (config.mode != ProjectMode.auto) return config.mode;
    final hasMain = files.any((f) {
      final rel = _relative(f);
      return _isPublicLibrary(rel) && p.posix.basename(rel).startsWith('main');
    });
    if (hasMain) return ProjectMode.app;
    try {
      final doc = loadYaml(pubspec.readAsStringSync());
      if (doc is Map && '${doc['publish_to']}' == 'none') {
        return ProjectMode.app;
      }
    } on YamlException {
      // A broken pubspec fails resolution anyway; assume a package.
    }
    return ProjectMode.package;
  }

  /// Every `.dart` file of this package, nested packages and build output
  /// excluded. Symlinks are not followed.
  List<String> _discover() {
    final out = <String>[];
    void walk(Directory dir, {required bool top}) {
      final entries = dir.listSync(followLinks: false)
        ..sort((a, b) => a.path.compareTo(b.path));
      for (final entity in entries) {
        final name = p.basename(entity.path);
        if (entity is Directory) {
          if (name.startsWith('.')) continue;
          if (top && _skippedDirectories.contains(name)) continue;
          if (File(p.join(entity.path, 'pubspec.yaml')).existsSync()) {
            continue; // nested package (example/, packages/*)
          }
          walk(entity, top: false);
        } else if (entity is File && name.endsWith('.dart')) {
          out.add(p.normalize(entity.absolute.path));
        }
      }
    }

    walk(Directory(root), top: true);
    return out;
  }
}
