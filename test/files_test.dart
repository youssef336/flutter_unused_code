import 'package:flutter_unused_code/flutter_unused_code.dart';
import 'package:test/test.dart';

import 'support/fixture.dart';

void main() {
  group('unused files', () {
    late UnusedCodeReport report;

    setUpAll(() async {
      report = await analyzeFiles({
        'lib/main.dart': '''
import 'imported.dart';
import 'conditional_stub.dart'
    if (dart.library.io) 'conditional_io.dart';
export 'exported.dart';
part 'main_part.dart';

void main() => run(Imported(), describe());
''',
        'lib/main_part.dart': '''
part of 'main.dart';

void run(Object a, Object b) {}
''',
        'lib/imported.dart': '''
import 'transitive.dart';

class Imported {
  final t = Transitive();
}
''',
        'lib/transitive.dart': 'class Transitive {}\n',
        'lib/exported.dart': 'void exportedOnly() {}\n',
        'lib/conditional_stub.dart': "String describe() => 'stub';\n",
        'lib/conditional_io.dart': "String describe() => 'io';\n",
        'lib/orphan.dart': "import 'orphan_dep.dart';\n\nclass Orphan {}\n",
        'lib/orphan_dep.dart': 'class OrphanDep {}\n',
        'lib/src/only_tested.dart': 'int answer() => 42;\n',
        'lib/models/user.g.dart': '// GENERATED CODE\nclass Gen {}\n',
        'lib/firebase_options.dart':
            '// File generated by FlutterFire CLI.\nclass Opts {}\n',
        'lib/legacy/old.dart': '// unused_code:ignore_file\nclass Old {}\n',
        'bin/tool.dart': 'void main() {}\n',
        'test/only_tested_test.dart': '''
import 'package:app/src/only_tested.dart';

void main() => answer();
''',
      });
    });

    test('reports libraries no entry point reaches', () {
      expect(
        report.files,
        unorderedEquals(['lib/orphan.dart', 'lib/orphan_dep.dart']),
      );
    });

    test('follows imports, exports, parts and every conditional branch', () {
      for (final reached in [
        'lib/imported.dart',
        'lib/transitive.dart',
        'lib/exported.dart',
        'lib/main_part.dart',
        'lib/conditional_stub.dart',
        'lib/conditional_io.dart',
      ]) {
        expect(report.files, isNot(contains(reached)), reason: reached);
      }
    });

    test('tests are entry points', () {
      expect(report.files, isNot(contains('lib/src/only_tested.dart')));
    });

    test('generated and ignored files are never reported', () {
      expect(report.files, isNot(contains('lib/models/user.g.dart')));
      expect(report.files, isNot(contains('lib/firebase_options.dart')));
      expect(report.files, isNot(contains('lib/legacy/old.dart')));
      expect(report.names, isNot(contains('Old')));
    });

    test('declarations inside an unused file are not repeated', () {
      expect(report.names, isNot(contains('Orphan')));
      expect(report.names, isNot(contains('OrphanDep')));
    });

    test('a file finding counts its lines', () {
      final orphan = report.findings.firstWhere(
        (f) => f.path == 'lib/orphan.dart',
      );
      expect(orphan.category, FindingCategory.file);
      expect(orphan.lines, 4);
    });

    test('a public member of a reachable but unused export is reported', () {
      expect(report.names, contains('exportedOnly'));
    });
  });

  test('entry-point globs from the config keep files alive', () async {
    final report = await analyzeFiles({
      'lib/main.dart': 'void main() {}\n',
      'lib/workers/sync.dart': "import '../helper.dart';\nvoid sync() {}\n",
      'lib/helper.dart': 'void help() {}\n',
    }, config: UnusedCodeConfig(entryPoints: ['lib/workers/*.dart']));
    expect(report.files, isEmpty);
    expect(report.names, contains('sync'));
  });

  test('excluded files are neither reported nor dead ends', () async {
    final report = await analyzeFiles({
      'lib/main.dart': 'void main() {}\n',
      'lib/legacy/a.dart': "import '../kept.dart';\nvoid a() => kept();\n",
      'lib/kept.dart': 'void kept() {}\n',
    }, config: UnusedCodeConfig(exclude: ['lib/legacy/**']));
    expect(report.files, isEmpty);
    expect(report.names, isEmpty);
  });
}
